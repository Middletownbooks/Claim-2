#!/usr/bin/env python3
"""Generate kaggle/kaggle_shard.py with the C sources embedded.

GENERATED, NOT HAND-MAINTAINED.  A hand-copied duplicate of cog.c and search.c
would drift from the originals and the drift would be invisible -- the notebook
would still build, still print level counts, and still be wrong.  This reads the
real sources every time, and the generated script re-runs the gate before it
does any work, so a stale or corrupted copy stops rather than producing numbers.
"""
import hashlib, pathlib, sys

HERE = pathlib.Path(__file__).resolve().parent
C = HERE.parent / "c"
FILES = ["cog.h", "cog.c", "search.c"]

src = {f: (C / f).read_text() for f in FILES}
digest = hashlib.sha256("".join(src[f] for f in FILES).encode()).hexdigest()[:16]

parts = ["#!/usr/bin/env python3\n",
         '"""Self-contained (m,7) shard runner for a wall-clock-capped notebook.\n\n',
         "GENERATED by kaggle/make_bundle.py from the C sources; do not edit here.\n",
         "Source digest: %s\n\n" % digest,
         "WHAT IT DOES, in order, and it stops at the first thing that fails:\n",
         "  1. probes the environment -- compiler, whether a filesystem will execute\n",
         "     what we build on it, cores, memory;\n",
         "  2. writes and builds the C;\n",
         "  3. RUNS THE GATE: the exact (7,7) level counts, both Theorem 7\n",
         "     configurations, and refuses to continue if either differs by one node;\n",
         "  4. dumps its own level-4 frontier, which needs no Python;\n",
         "  5. runs the shards it was assigned, writing one JSON per shard as it\n",
         "     finishes, so a session killed by the wall clock loses at most one.\n",
         '"""\n',
         "import json, os, pathlib, shutil, subprocess, sys, time\n\n",
         "SRC_DIGEST = %r\n" % digest,
         "SOURCES = {\n"]
for f in FILES:
    parts.append("    %r: r'''%s''',\n" % (f, src[f].replace("'''", "'\\''\\''")))
parts.append("}\n")
parts.append('''
# ---------------------------------------------------------------- configuration
M        = int(os.environ.get("ZM", "11"))      # the (m,7) case
N        = int(os.environ.get("ZN", "7"))
LEVEL    = int(os.environ.get("ZLEVEL", "4"))   # split level for the frontier
NSHARDS  = int(os.environ.get("ZNSHARDS", "1000"))
FIRST    = int(os.environ.get("ZFIRST", "0"))   # first shard index this session takes
COUNT    = int(os.environ.get("ZCOUNT", "1000000"))
THREADS  = int(os.environ.get("ZTHREADS", "0")) or (os.cpu_count() or 1)
WALL     = float(os.environ.get("ZWALL", "39600"))   # stop starting shards after this
OUT      = pathlib.Path(os.environ.get("ZOUT", "/kaggle/working/zout"))
PREV     = os.environ.get("ZPREV", "/kaggle/input")  # earlier sessions' outputs

GATE = {
    "": [1, 13, 377, 29099, 801503, 14623179, 809438],
    "24": [1, 12, 329, 25346, 615817, 9827953, 809438],
}

def sh(cmd, **kw):
    return subprocess.run(cmd, shell=True, capture_output=True, text=True, **kw)

# ------------------------------------------------------------------- 1. probe
def probe():
    print("=== environment ===")
    print("python     :", sys.version.split()[0])
    print("cpus       :", os.cpu_count())
    cc = None
    for c in ("cc", "gcc", "clang"):
        r = sh("%s --version" % c)
        if r.returncode == 0:
            cc = c
            print("compiler   : %s -> %s" % (c, r.stdout.splitlines()[0]))
            break
    if not cc:
        print("compiler   : NONE FOUND.  Install one with: apt-get -qq install -y build-essential")
    try:
        mem = int([l for l in open("/proc/meminfo") if l.startswith("MemTotal")][0].split()[1]) // 1024
        print("memory     : %d MB" % mem)
    except Exception:
        pass
    # Will a filesystem actually EXECUTE what we build on it?  A noexec mount is
    # the one plausible blocker and it is cheaper to test than to look up.
    workdir = None
    for d in ("/kaggle/working", "/tmp", os.getcwd()):
        try:
            p = pathlib.Path(d) / ".exectest.sh"
            p.write_text("#!/bin/sh\\necho ok\\n")
            p.chmod(0o755)
            r = sh(str(p))
            ok = (r.returncode == 0 and r.stdout.strip() == "ok")
            print("exec from  : %-18s %s" % (d, "YES" if ok else "NO (%s)" % (r.stderr.strip()[:60] or "rc=%d" % r.returncode)))
            p.unlink(missing_ok=True)
            if ok and workdir is None:
                workdir = pathlib.Path(d)
        except Exception as e:
            print("exec from  : %-18s NO (%s)" % (d, e))
    print("free disk  :", shutil.disk_usage("/").free // (1 << 30), "GB on /")
    return cc, workdir

# -------------------------------------------------------------- 2. write + build
def build(cc, wd):
    bd = wd / "zbuild"
    bd.mkdir(parents=True, exist_ok=True)
    for name, text in SOURCES.items():
        (bd / name).write_text(text)
    flags = "-O3 -funroll-loops -std=gnu11"
    r = sh("%s %s -march=native -o zsearch search.c cog.c -lpthread" % (cc, flags), cwd=bd)
    if r.returncode != 0:
        print("-march=native failed, retrying without it")
        r = sh("%s %s -o zsearch search.c cog.c -lpthread" % (cc, flags), cwd=bd)
    if r.returncode != 0:
        print(r.stderr[-2000:]); sys.exit("BUILD FAILED")
    print("built %s" % (bd / "zsearch"))
    return bd / "zsearch"

# ------------------------------------------------------------------- 3. the gate
def gate(exe):
    print("=== gate: the exact (7,7) level counts, or we stop ===")
    for thm7, want in GATE.items():
        r = sh("%s -m 7 -n 7 %s" % (exe, ("-thm7 " + thm7) if thm7 else ""))
        if r.returncode != 0:
            print(r.stderr[-1000:]); sys.exit("GATE: the binary failed to run")
        d = json.loads(r.stdout)
        got = d["level_counts"]
        print("  thm7=%-3s %s  %s  (%.1f s)"
              % (thm7 or "off", got, "ok" if got == want else "FAIL, want %s" % want, d["elapsed_s"]))
        if got != want:
            sys.exit("GATE FAILED -- nothing this binary prints can be trusted")
    print("  gate passed")

# ---------------------------------------------------------------- 4. the frontier
def frontier(exe, wd):
    f = wd / ("frontier_m%d_L%d.txt" % (M, LEVEL))
    if f.exists() and f.stat().st_size > 0:
        print("frontier already present: %s" % f)
    else:
        r = sh("%s -m %d -n %d -d %d -dump %s" % (exe, M, N, LEVEL, f))
        if r.returncode != 0:
            print(r.stderr[-1000:]); sys.exit("frontier dump failed")
        d = json.loads(r.stdout)
        print("frontier: %d prefixes at level %d, counts to L %s"
              % (sum(1 for _ in open(f)), LEVEL, d["level_counts"][:LEVEL]))
    return f

# ------------------------------------------------------------------- 5. the work
def already_done():
    done = set()
    for root in (OUT, pathlib.Path(PREV)):
        if not root.exists():
            continue
        for p in root.rglob("shard_m%d_L%d_*of%d.json" % (M, LEVEL, NSHARDS)):
            try:
                d = json.loads(p.read_text())
                if d.get("complete"):
                    done.add(d["shard"])
            except Exception:
                pass
    return done

def main():
    cc, wd = probe()
    if not cc:
        sys.exit("no compiler")
    if wd is None:
        sys.exit("no filesystem on this host will execute a freshly built binary")
    exe = build(cc, wd)
    gate(exe)
    f = frontier(exe, wd)
    OUT.mkdir(parents=True, exist_ok=True)
    done = already_done()
    print("=== shards: %d total, %d already complete, this session takes %d from %d ==="
          % (NSHARDS, len(done), COUNT, FIRST))
    t0 = time.time()
    for i in range(FIRST, min(FIRST + COUNT, NSHARDS)):
        if i in done:
            continue
        if time.time() - t0 > WALL:
            print("wall budget reached; stopping before shard %d" % i)
            break
        r = sh("%s -m %d -n %d -startfile %s -shard %d -of %d -threads %d"
               % (exe, M, N, f, i, NSHARDS, THREADS))
        if r.returncode != 0:
            print(r.stderr[-1000:]); sys.exit("shard %d failed" % i)
        d = json.loads(r.stdout)
        d["complete"] = not d["aborted"]
        d["src_digest"] = SRC_DIGEST
        (OUT / ("shard_m%d_L%d_%dof%d.json" % (M, LEVEL, i, NSHARDS))).write_text(json.dumps(d) + "\\n")
        print("  shard %4d: %5d prefixes, %13d nodes, %7.1f s wall, %8.0f nodes/core-s"
              % (i, d["prefixes_done"], d["total_nodes"], d["elapsed_s"], d["nodes_per_core_s"]),
              flush=True)
    print("=== session done; %d shard files in %s ===" % (len(list(OUT.glob("shard_*.json"))), OUT))

if __name__ == "__main__":
    main()
''')
open('kaggle/kaggle_shard.py', 'w').write("".join(parts))
print("wrote kaggle/kaggle_shard.py (%d KB, digest %s)" % (len(open('kaggle/kaggle_shard.py').read()) // 1024, digest))
