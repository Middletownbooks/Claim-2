#!/usr/bin/env python3
"""Generate kaggle/kaggle_shard.py: the C sources plus driver.py, embedded.

GENERATED, NOT HAND-MAINTAINED.  A hand-copied duplicate of cog.c, search.c or
the driver would drift from the originals and the drift would be invisible --
the notebook would still build, still print level counts, and still be wrong.
This reads the real files every time and stamps a digest of what it embedded
into the output and into every shard JSON, and the generated script re-runs the
gate before doing any work, so a stale or corrupted copy stops rather than
producing numbers.

The driver lives in driver.py rather than inside a string here: an earlier
version embedded it as a literal and the nested triple quotes silently broke
the generator, leaving the bundle with a fresh C and a four-hour-old driver.
"""
import hashlib, pathlib

HERE = pathlib.Path(__file__).resolve().parent
C = HERE.parent / "c"
CFILES = ["cog.h", "cog.c", "search.c"]

src = {f: (C / f).read_text() for f in CFILES}
driver = (HERE / "driver.py").read_text()
digest = hashlib.sha256(("".join(src[f] for f in CFILES) + driver).encode()).hexdigest()[:16]

head = '''#!/usr/bin/env python3
"""Self-contained (m,7) calibration and shard runner for a wall-clock-capped notebook.

GENERATED by kaggle/make_bundle.py from the C sources and driver.py.  Do not edit
here.  Source digest: %s

TWO MODES.
  ZMODE=calibrate (the default)  probe the host, build, gate, then run a FIXED,
      DETERMINISTIC work quantum at 1..N threads and compare every number against
      the reference measured where this bundle was built.  Twenty minutes, and it
      answers the only question that matters before committing sessions: what is
      this host actually worth?
  ZMODE=sweep  the production run, in shards, idempotent, resumable across
      sessions, with per-shard rate drift flagged and the gate re-run at the end
      to expose intra-session slowdown.

IT STOPS AT THE FIRST THING THAT FAILS: no compiler, no filesystem that will
execute a fresh binary, a gate that is off by one node, a work quantum that is
not identical between thread counts, or a survivor file that disagrees with its
histogram.
"""
import json, os, pathlib, shutil, subprocess, sys, time

SRC_DIGEST = %r
SOURCES = {
''' % (digest, digest)

parts = [head]
for f in CFILES:
    parts.append("    %r: r\'\'\'%s\'\'\',\n" % (f, src[f]))
parts.append("}\n\n")
parts.append(driver)
out = HERE / "kaggle_shard.py"
out.write_text("".join(parts))
print("wrote %s (%d KB, digest %s)" % (out.name, len(out.read_text()) // 1024, digest))
